static u8 xtime(u8 x)
{
    return (u8)((unsigned)(x << 1) ^ ((unsigned)(x >> 7) * 0x1Bu));
}

// FIPS-197 4.2 key expansion (Nb=Nk=4, Nr=10).
int aes128_expand_key(u32 rk[44], const u8 key[16])
{
    u8 rc = 1;
    int i;
    if (!rk || !key) return -1;
    for (i = 0; i < 4; i++)
        rk[i] = ((u32)key[4*i] << 24) | ((u32)key[4*i+1] << 16) |
                ((u32)key[4*i+2] << 8) |  (u32)key[4*i+3];
    for (i = 4; i < 44; i++) {
        u32 t = rk[i-1];
        if (i % 4 == 0) {                       // RotWord + SubWord + Rcon
            t = (t << 8) | (t >> 24);
            t = ((u32)SBOX[(t >> 24) & 0xFF] << 24) | ((u32)SBOX[(t >> 16) & 0xFF] << 16) |
                ((u32)SBOX[(t >>  8) & 0xFF] <<  8) |  (u32)SBOX[t & 0xFF];
            t ^= (u32)rc << 24;
            rc = xtime(rc);
        }
        rk[i] = rk[i-4] ^ t;
    }
    return 0;
}

// State convention: linear 16 bytes, state[i] = in[i]; row = i % 4,
// column = i / 4 (FIPS-197 3.4 input mapping).

static void sub_bytes(u8 s[16], const u8 box[256])
{
    int i;
    for (i = 0; i < 16; i++) s[i] = box[s[i]];
}

static void shift_rows(u8 s[16])
{
    u8 t;
    t = s[1];  s[1]  = s[5];  s[5]  = s[9];  s[9]  = s[13]; s[13] = t;   // row1 <<1
    t = s[2];  s[2]  = s[10]; s[10] = t;
    t = s[6];  s[6]  = s[14]; s[14] = t;                                  // row2 <<2
    t = s[15]; s[15] = s[11]; s[11] = s[7];  s[7]  = s[3];  s[3]  = t;   // row3 <<3
}

static void inv_shift_rows(u8 s[16])
{
    u8 t;
    t = s[13]; s[13] = s[9];  s[9]  = s[5];  s[5]  = s[1];  s[1]  = t;   // row1 >>1
    t = s[2];  s[2]  = s[10]; s[10] = t;
    t = s[6];  s[6]  = s[14]; s[14] = t;                                  // row2 >>2
    t = s[3];  s[3]  = s[7];  s[7]  = s[11]; s[11] = s[15]; s[15] = t;   // row3 >>3
}

static void mix_columns(u8 s[16])
{
    int c;
    for (c = 0; c < 4; c++) {
        u8 *p = s + 4*c;
        u8 a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];
        p[0] = (u8)(xtime(a0) ^ (u8)(xtime(a1) ^ a1) ^ a2 ^ a3);
        p[1] = (u8)(a0 ^ xtime(a1) ^ (u8)(xtime(a2) ^ a2) ^ a3);
        p[2] = (u8)(a0 ^ a1 ^ xtime(a2) ^ (u8)(xtime(a3) ^ a3));
        p[3] = (u8)((u8)(xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3));
    }
}

static u8 mul9 (u8 x) { u8 x2 = xtime(x), x4 = xtime(x2), x8 = xtime(x4);
                        return (u8)(x8 ^ x); }
static u8 mul11(u8 x) { u8 x2 = xtime(x), x4 = xtime(x2), x8 = xtime(x4);
                        return (u8)(x8 ^ x2 ^ x); }
static u8 mul13(u8 x) { u8 x2 = xtime(x), x4 = xtime(x2), x8 = xtime(x4);
                        return (u8)(x8 ^ x4 ^ x); }
static u8 mul14(u8 x) { u8 x2 = xtime(x), x4 = xtime(x2), x8 = xtime(x4);
                        return (u8)(x8 ^ x4 ^ x2); }

static void inv_mix_columns(u8 s[16])
{
    int c;
    for (c = 0; c < 4; c++) {
        u8 *p = s + 4*c;
        u8 a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];
        p[0] = (u8)(mul14(a0) ^ mul11(a1) ^ mul13(a2) ^ mul9 (a3));
        p[1] = (u8)(mul9 (a0) ^ mul14(a1) ^ mul11(a2) ^ mul13(a3));
        p[2] = (u8)(mul13(a0) ^ mul9 (a1) ^ mul14(a2) ^ mul11(a3));
        p[3] = (u8)(mul11(a0) ^ mul13(a1) ^ mul9 (a2) ^ mul14(a3));
    }
}

static void add_round_key(u8 s[16], const u32 rk[44], int round)
{
    int c;
    for (c = 0; c < 4; c++) {
        u32 k = rk[round*4 + c];
        s[4*c+0] ^= (u8)(k >> 24);
        s[4*c+1] ^= (u8)(k >> 16);
        s[4*c+2] ^= (u8)(k >>  8);
        s[4*c+3] ^= (u8)(k);
    }
}

void aes128_encrypt_block(const u32 rk[44], const u8 in[16], u8 out[16])
{
    u8 s[16];
    int r;
    memcpy(s, in, 16);
    add_round_key(s, rk, 0);
    for (r = 1; r <= 9; r++) {
        sub_bytes(s, SBOX);
        shift_rows(s);
        mix_columns(s);
        add_round_key(s, rk, r);
    }
    sub_bytes(s, SBOX);
    shift_rows(s);
    add_round_key(s, rk, 10);
    memcpy(out, s, 16);
}

void aes128_decrypt_block(const u32 rk[44], const u8 in[16], u8 out[16])
{
    u8 s[16];
    int r;
    memcpy(s, in, 16);
    add_round_key(s, rk, 10);
    for (r = 9; r >= 1; r--) {
        inv_shift_rows(s);
        sub_bytes(s, INV_SBOX);
        add_round_key(s, rk, r);
        inv_mix_columns(s);
    }
    inv_shift_rows(s);
    sub_bytes(s, INV_SBOX);
    add_round_key(s, rk, 0);
    memcpy(out, s, 16);
}

int aes128_cbc_encrypt(const u8 key[16], const u8 iv[16], u8 *buf, u32 len)
{
    u32 rk[44];
    u8 chain[16];
    u32 off;
    int i;
    if (!key || !buf || len == 0 || (len % 16) != 0) return -1;
    if (aes128_expand_key(rk, key) != 0) return -1;
    if (iv) memcpy(chain, iv, 16); else memset(chain, 0, 16);   // NULL-IV convention
    for (off = 0; off < len; off += 16) {
        for (i = 0; i < 16; i++) buf[off + i] ^= chain[i];
        aes128_encrypt_block(rk, buf + off, buf + off);
        memcpy(chain, buf + off, 16);
    }
    return 0;
}

int aes128_cbc_decrypt(const u8 key[16], const u8 iv[16], u8 *buf, u32 len)
{
    u32 rk[44];
    u8 chain[16], ct[16];
    u32 off;
    int i;
    if (!key || !buf || len == 0 || (len % 16) != 0) return -1;
    if (aes128_expand_key(rk, key) != 0) return -1;
    if (iv) memcpy(chain, iv, 16); else memset(chain, 0, 16);   // NULL-IV convention
    for (off = 0; off < len; off += 16) {
        memcpy(ct, buf + off, 16);
        aes128_decrypt_block(rk, buf + off, buf + off);
        for (i = 0; i < 16; i++) buf[off + i] ^= chain[i];
        memcpy(chain, ct, 16);
    }
    return 0;
}
